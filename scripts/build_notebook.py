"""Build a self-contained Kaggle submission notebook around one of our policies.

The policy module's source is embedded verbatim, because internet access is off
on Kaggle and this repository's package cannot be installed there. The policy is
wrapped in a subclass of smart_buildings_inference_server.Policy; the import
lines and the server call mirror the organizers' TransferPolicy Notebook
(reference/official/submission-example/transferpolicy-notebook.ipynb).
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import time

from workspace import ROOT

KAGGLE_ROOT = "/kaggle/input/competitions/neurips-2026-smart-buildings"
COMPETITION = "neurips-2026-smart-buildings"


def cell(kind, source):
    lines = source.strip("\n").split("\n")
    entry = {"cell_type": kind, "metadata": {},
             "source": [line + "\n" for line in lines[:-1]] + [lines[-1]]}
    if kind == "code":
        entry.update(execution_count=None, outputs=[])
    return entry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--module", default="packages/smart_building/policies/constant.py")
    parser.add_argument("--class-name", default="ConstantPolicy")
    parser.add_argument("--slug", default="sb-b0-constant-pipeline-check")
    parser.add_argument("--title", default="SB B0 constant pipeline check")
    parser.add_argument("--username", default="USERNAME",
                        help="Kaggle username for kernel-metadata.json; fill in before pushing")
    parser.add_argument("--out", default="data/submissions/b0")
    args = parser.parse_args()
    # Kaggle derives the notebook URL from the title; a different slug in the id makes
    # later pushes and status calls address a kernel that does not exist.
    if re.sub(r"[^a-z0-9]+", "-", args.title.lower()).strip("-") != args.slug:
        parser.error("--slug must equal the slug Kaggle derives from --title")
    module = ROOT / args.module
    source = module.read_text(encoding="utf-8")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    header = f"""# {args.title}

Generated by `scripts/build_notebook.py` on {time.strftime("%Y-%m-%d")}.
Embedded policy: `{args.module}` (`{args.class_name}`), SHA-256 `{digest}`.
"""
    setup = f"""import sys
sys.path.append('{KAGGLE_ROOT}/kaggle_evaluation')

import numpy as np
from kaggle_evaluation import smart_buildings_inference_server

COMPETITION_DATA_FOLDER = '{KAGGLE_ROOT}/'
"""
    wrapper = f"""class SubmissionPolicy(smart_buildings_inference_server.Policy):
    def __init__(self, building_meta_data, action_spec):
        super().__init__(building_meta_data, action_spec)
        self.policy = {args.class_name}(building_meta_data, action_spec)

    def get_action(self, obs):
        return self.policy.get_action(obs)


smart_buildings_inference_server.SmartBuildingsInferenceServer(SubmissionPolicy).run(
    competition_data_folder=COMPETITION_DATA_FOLDER,
)
"""
    notebook = {
        "cells": [cell("markdown", header), cell("code", setup), cell("code", source),
                  cell("code", wrapper)],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.13.15"},
        },
        "nbformat": 4, "nbformat_minor": 4,
    }
    out = ROOT / args.out
    out.mkdir(parents=True, exist_ok=True)
    code_file = f"{args.slug}.ipynb"
    (out / code_file).write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n",
                                 encoding="utf-8", newline="\n")
    metadata = {
        "id": f"{args.username}/{args.slug}", "title": args.title, "code_file": code_file,
        "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": False, "enable_tpu": False, "enable_internet": False,
        "dataset_sources": [], "competition_sources": [COMPETITION], "kernel_sources": [],
        "model_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n",
                                              encoding="utf-8", newline="\n")
    print(f"Wrote {(out / code_file).relative_to(ROOT).as_posix()} (policy sha256 {digest})")


if __name__ == "__main__":
    main()

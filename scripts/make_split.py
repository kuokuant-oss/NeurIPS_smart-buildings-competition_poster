def inner_definition(base):
    """REQ-007 (decided 2026-10-17 14:55): 12 INNER buildings (6 shipped size, 6 DEFAULT_RANGES), shared by
    the 5 folds; fold k: 6 of them (3 + 3 by stratum), each with one of fold k's 4 training stations and
    one seasonal preset, every station and every season at least once per fold. v1.json is not changed."""
    split = {k: base[k] for k in ("version", "protocol", "generator", "size_strata", "stations", "folds",
                                  "fold_order", "training_windows")}
    split.update({
        "registry_ids": ["D-E03", "D-E04", "D-E05", "D-E06", "D-E07", "D-E12", "REQ-007"],
        "command": "python3 -B scripts/workspace.py make-split --inner",
        "base_split": {"file": "configs/splits/v1.json", "sha256": hashlib.sha256(SPLIT_FILE.read_bytes()).hexdigest()},
        "pools": {"inner": {
            "seed_range": base["pools"]["inner"]["seed_range"], "buildings": 12,
            "strata": ["shipped"] * 6 + ["default"] * 6,
            "draw": {"rng_label": "split-v1/inner", "method": base["pools"]["val"]["draw"]["method"]},
            "episodes": {"per_fold": 6, "per_stratum_per_fold": 3, "presets": INNER_PRESETS,
                         "rng_label": "split-v1/inner-episodes/fold<k>",
                         "method": "random.Random(sha256(label)[:8]): sample 3 + 3 buildings by stratum; stations = "
                                   "the 4 training stations + 2 drawn, presets = the 4 seasons + 2 drawn, each list "
                                   "shuffled and paired with the shuffled buildings; redraw until the 6 station-preset "
                                   "pairs are distinct (attempt counter in the label)"},
            "disjoint_from": {"train": base["pools"]["train"]["generated_seed_range"],
                              "train_shipped_seeds": sorted(base["pools"]["train"]["shipped_buildings"].values()),
                              "val": base["pools"]["val"]["seed_range"], "lock": base["pools"]["lock"]["seed_range"]}}},
    })
    return split


def inner_episodes(split):
    from smart_building.scenarios import factory
    pool = split["pools"]["inner"]
    weather = UPSTREAM / "smart_buildings/weather"
    by_stratum = {s: [seed for seed, st in zip(pool["seeds"], pool["strata"]) if st == s] for s in ("shipped", "default")}
    rows = []
    for entry in split["folds"]:
        stations = entry["training_stations"]
        for attempt in range(1000):
            rng = factory.draw_rng(f"split-v1/inner-episodes/fold{entry['fold']}/{attempt}")
            seeds = rng.sample(by_stratum["shipped"], 3) + rng.sample(by_stratum["default"], 3)
            rng.shuffle(seeds)
            chosen_stations = stations + [rng.choice(stations) for _ in range(2)]
            presets = INNER_PRESETS + [rng.choice(INNER_PRESETS) for _ in range(2)]
            rng.shuffle(chosen_stations)
            rng.shuffle(presets)
            pairs = list(zip(chosen_stations, presets))
            if len(set(pairs)) == 6:
                break
        for seed, (station, preset) in zip(seeds, pairs):
            window = f"{station}_{preset}"
            rows.append({"fold": entry["fold"], "building": f"building_{seed:04d}", "seed": seed,
                         "stratum": pool["strata"][pool["seeds"].index(seed)], "weather": window, "station": station,
                         "preset": preset, "start": str(read_yaml(weather / f"{window}.yaml")["start_timestamp"]),
                         "class": "S2", "draw_attempt": attempt})
    return rows


def check_inner(split, base):
    """Registration checks (as make-split): disjoint pools, strata, per-fold balance."""
    pool = split["pools"]["inner"]
    low, high = pool["seed_range"]
    problems = []
    if not all(low <= s < high for s in pool["seeds"]) or len(set(pool["seeds"])) != 12:
        problems.append("INNER seeds outside their range or repeated")
    others = set(base["pools"]["val"]["seeds"]) | set(base["pools"]["train"]["shipped_buildings"].values())
    if others & set(pool["seeds"]):
        problems.append("INNER overlaps VAL or the shipped TRAIN buildings")
    if sorted(pool["strata"]) != sorted(["shipped"] * 6 + ["default"] * 6):
        problems.append("strata are not 6 + 6")
    for entry in split["folds"]:
        rows = [r for r in split["scenarios"]["inner"] if r["fold"] == entry["fold"]]
        ok = (len(rows) == 6 and len({r["building"] for r in rows}) == 6
              and sorted(r["stratum"] for r in rows) == ["default"] * 3 + ["shipped"] * 3
              and {r["station"] for r in rows} == set(entry["training_stations"])
              and {r["preset"] for r in rows} == set(INNER_PRESETS)
              and entry["held_out_station"] not in {r["station"] for r in rows}
              and len({r["weather"] for r in rows}) == 6)
        if not ok:
            problems.append(f"fold {entry['fold']} breaks the REQ-007 balance")
    return problems



"""Make and register the validation split (build plan WP1 1.1; validation-v1 §2).

    make-split            write configs/splits/v1.json and generate the VAL pool into data/processed/
    make-split --check    regenerate in a scratch mirror under .tmp/ and compare every SHA-256

Registered decisions: D-E03 (disjoint pools above seed 10000, each generated by
one fixed command, materials stratified across the whole pool), D-E04 (VAL and
LOCK half "shipped size", half DEFAULT_RANGES), D-E05 (shipped size = width
318-430, height 188-301, min_room_size 25-35), D-E06 (leave-one-station-out,
fold k = VAL group k x held-out station presets _1 _3 _5 _7), D-E12 (training
windows: any Sunday-06:00, 30-day window of a training station CSV, official
convection coefficient).

Implementation parameters under those rows, recorded in the split file for the
reviewer: pool seed ranges TRAIN 10000-19999, INNER 20000-29999, VAL
30000-39999, LOCK 40000-49999 (D-E03 "above 10000", notes/07 P1.1 "drawn with a
fixed random seed"); the draw RNG is seeded from SHA-256 of "split-v1/<pool>";
folds follow the alphabetical station order; inside each VAL group the first
three buildings are "shipped" size and the last three DEFAULT_RANGES. Seeds
whose floor plan fails the official zone-area check are skipped (notes/01 §E).
LOCK seeds are neither drawn nor generated here (D-E07: reviewer-built lockbox
jobs only); INNER waits for REQ-007.
"""

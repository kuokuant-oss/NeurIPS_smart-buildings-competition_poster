TRAIN_FILE = ROOT / "configs/splits" / f"{VERSION}-train.json"
TRAIN_BUILDINGS = 80
J7_ITERATIONS, J7_EPISODES = 20, 4  # docs/plan/baseline-v1-stage45.md §2 (E = 4, 20 iterations)


def train_definition(base, inner):
    """WP4 (stage45 §2, REQ-005): 80 TRAIN buildings, 40 shipped size + 40 DEFAULT_RANGES (D-E04 extended
    as for INNER), shared by the folds; J7 list: per fold 20 iterations x 4 rollouts, every rollout a
    different building x one of fold k's 4 training stations x a seasonal preset."""
    split = {k: base[k] for k in ("version", "protocol", "generator", "size_strata", "stations", "folds",
                                  "fold_order", "training_windows")}
    split.update({
        "registry_ids": ["D-E03", "D-E04", "D-E05", "D-E06", "D-E07", "D-E12", "REQ-005", "D-L10"],
        "command": "python3 -B scripts/workspace.py make-split --train",
        "base_split": {"file": "configs/splits/v1.json", "sha256": hashlib.sha256(SPLIT_FILE.read_bytes()).hexdigest()},
        "inner_split": {"file": "configs/splits/v1-inner.json", "sha256": hashlib.sha256(INNER_FILE.read_bytes()).hexdigest()},
        "pools": {"train": {
            "seed_range": base["pools"]["train"]["generated_seed_range"], "buildings": TRAIN_BUILDINGS,
            "strata": ["shipped", "default"] * (TRAIN_BUILDINGS // 2),
            "draw": {"rng_label": "split-v1/train", "method": base["pools"]["val"]["draw"]["method"]},
            "j7": {"iterations": J7_ITERATIONS, "episodes_per_iteration": J7_EPISODES, "presets": INNER_PRESETS,
                   "rng_label": "split-v1/j7/fold<k>",
                   "method": "per fold: the 80 buildings shuffled with shipped and default alternating in pairs; "
                             "iteration i uses buildings 4i..4i+3, each of the 4 training stations once (shuffled) and "
                             "the 4 presets once (a 4 x 4 Latin square over iterations 4j..4j+3), so every station, "
                             "every preset and every station-preset pair is equally used in the fold"},
            "disjoint_from": {"val": base["pools"]["val"]["seed_range"], "inner": inner["pools"]["inner"]["seed_range"],
                              "lock": base["pools"]["lock"]["seed_range"],
                              "train_shipped_seeds": sorted(base["pools"]["train"]["shipped_buildings"].values())}}},
    })
    return split


def j7_episodes(split):
    from smart_building.scenarios import factory
    pool = split["pools"]["train"]
    weather = UPSTREAM / "smart_buildings/weather"
    shipped = [s for s, st in zip(pool["seeds"], pool["strata"]) if st == "shipped"]
    default = [s for s, st in zip(pool["seeds"], pool["strata"]) if st == "default"]
    rows = []
    for entry in split["folds"]:
        rng = factory.draw_rng(f"split-v1/j7/fold{entry['fold']}")
        a, b = list(shipped), list(default)
        rng.shuffle(a)
        rng.shuffle(b)
        buildings = [x for pair in zip(a, b) for x in pair]  # 2 shipped + 2 default per iteration
        for block in range(J7_ITERATIONS // 4):
            stations = list(entry["training_stations"])
            rng.shuffle(stations)
            presets = list(INNER_PRESETS)
            rng.shuffle(presets)
            for offset in range(4):
                iteration = block * 4 + offset
                for slot in range(J7_EPISODES):
                    seed = buildings[iteration * J7_EPISODES + slot]
                    station = stations[slot]
                    preset = presets[(slot + offset) % 4]  # Latin square: each pair once per block
                    window = f"{station}_{preset}"
                    rows.append({"fold": entry["fold"], "iteration": iteration + 1, "slot": slot,
                                 "building": f"building_{seed:04d}", "seed": seed,
                                 "stratum": pool["strata"][pool["seeds"].index(seed)], "weather": window,
                                 "station": station, "preset": preset,
                                 "start": str(read_yaml(weather / f"{window}.yaml")["start_timestamp"]), "class": "TRAIN"})
    return rows


def check_train(split, base, inner):
    pool = split["pools"]["train"]
    low, high = pool["seed_range"]
    problems = []
    if len(set(pool["seeds"])) != TRAIN_BUILDINGS or not all(low <= s < high for s in pool["seeds"]):
        problems.append("TRAIN seeds outside their range or repeated")
    if set(pool["seeds"]) & (set(base["pools"]["val"]["seeds"]) | set(inner["pools"]["inner"]["seeds"])
                             | set(base["pools"]["train"]["shipped_buildings"].values())):
        problems.append("TRAIN overlaps VAL, INNER or the shipped buildings")
    if sorted(pool["strata"]) != sorted(["shipped"] * 40 + ["default"] * 40):
        problems.append("strata are not 40 + 40")
    from collections import Counter
    for entry in split["folds"]:
        rows = [r for r in split["scenarios"]["train"] if r["fold"] == entry["fold"]]
        pairs = Counter((r["station"], r["preset"]) for r in rows)
        ok = (len(rows) == J7_ITERATIONS * J7_EPISODES and len({r["building"] for r in rows}) == TRAIN_BUILDINGS
              and set(r["station"] for r in rows) == set(entry["training_stations"])
              and set(pairs.values()) == {J7_ITERATIONS * J7_EPISODES // 16}
              and all(len({r["station"] for r in rows if r["iteration"] == i}) == 4 for i in range(1, J7_ITERATIONS + 1))
              and all(sorted(r["stratum"] for r in rows if r["iteration"] == i) == ["default", "default", "shipped", "shipped"]
                      for i in range(1, J7_ITERATIONS + 1)))
        if not ok:
            problems.append(f"fold {entry['fold']} breaks the J7 balance")
    return problems



"""The uploaded program (remote plan §3.3).

`remote build` turns a job into one folder per kernel: run.py (kernel_type
"script") with the code snapshot zip and the job definition embedded as base64,
plus kernel-metadata.json. run.py checks both SHA-256 values before anything
runs, unpacks into a writable scratch folder (never /kaggle/working, which
holds outputs only), and calls smart_building.remote.runner.main.

Work package SHA-256 = SHA-256 of "<code sha256>\\n<job sha256>\\n". The kernel
name, shard, attempt, mode and expected earlier outputs sit in the run.py header
outside that hash, so a smoke run, a full run and a continuation of the same
shard carry the same work package.
"""
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import zipfile

COMPETITION = "neurips-2026-smart-buildings"
# Never packed: data, scratch, official originals, environments, tools, git.
FORBIDDEN_TOP = {"data", ".tmp", "reference", "archive", ".venv", "tools", ".git"}
FORBIDDEN_NAMES = {"kaggle.json", ".env", "credentials.json", "access_token"}
SKIPPED = ("._", ".DS_Store", "__pycache__")
SECRET_PATTERNS = [
    re.compile(rb"KAGGLE_KEY\s*[=:]"),
    re.compile(rb"\"key\"\s*:\s*\"[A-Za-z0-9_\-]{20,}\""),
    re.compile(rb"KGAT_[A-Za-z0-9]{16,}"),
    re.compile(rb"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
    re.compile(rb"\bsk-[A-Za-z0-9]{20,}"),
]
ZIP_DATE = (1980, 1, 1, 0, 0, 0)
B64_LINE = 100


def sha256_bytes(data):
    return hashlib.sha256(data).hexdigest()


def package_sha256(code_sha256, job_sha256):
    return sha256_bytes(f"{code_sha256}\n{job_sha256}\n".encode("ascii"))


def slugify(title):
    """The URL name Kaggle derives from a kernel title (scripts/build_notebook.py check)."""
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def check_file(relative, data):
    """Raise if a file must not be uploaded."""
    parts = Path(relative).parts
    if parts[0] in FORBIDDEN_TOP:
        raise ValueError(f"{relative}: {parts[0]}/ is never packed (remote plan §3.3)")
    if Path(relative).name in FORBIDDEN_NAMES:
        raise ValueError(f"{relative}: credential-like file name")
    for pattern in SECRET_PATTERNS:
        if pattern.search(data):
            raise ValueError(f"{relative}: content looks like a secret ({pattern.pattern!r})")


def collect_code(root, patterns):
    """{relative posix path: bytes} for the job's code_paths, after the refusal rules."""
    root = Path(root).resolve()
    files = {}
    for pattern in patterns:
        top = Path(pattern).parts[0]
        if top in FORBIDDEN_TOP:
            raise ValueError(f"code path {pattern}: {top}/ is never packed (remote plan §3.3)")
        matches = sorted(root.glob(pattern))
        if not matches:
            raise FileNotFoundError(f"code path {pattern} matches nothing")
        for path in matches:
            if not path.is_file():
                continue
            relative = path.relative_to(root)
            if any(part.startswith(SKIPPED) for part in relative.parts) or path.suffix == ".pyc":
                continue
            data = path.read_bytes()
            check_file(relative.as_posix(), data)
            files[relative.as_posix()] = data
    return dict(sorted(files.items()))


def make_zip(files):
    """Deterministic zip: sorted names, fixed dates and permissions."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for name, data in sorted(files.items()):
            info = zipfile.ZipInfo(name, date_time=ZIP_DATE)
            info.external_attr = 0o644 << 16
            info.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(info, data, compresslevel=9)
    return buffer.getvalue()


def unzip(code_zip):
    """{name: bytes} of a code snapshot zip."""
    with zipfile.ZipFile(io.BytesIO(code_zip)) as archive:
        return {name: archive.read(name) for name in sorted(archive.namelist())}


def embedded_code(run_py_text):
    """The code snapshot zip embedded in a built run.py (CODE_ZIP_B64)."""
    import ast
    for node in ast.parse(run_py_text).body:
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", None) == "CODE_ZIP_B64":
            return base64.b64decode("".join(ast.literal_eval(node.value)))
    raise ValueError("run.py has no CODE_ZIP_B64")


def _b64_literal(data):
    text = base64.b64encode(data).decode("ascii")
    lines = [text[i:i + B64_LINE] for i in range(0, len(text), B64_LINE)] or [""]
    return "(\n" + "\n".join(f'    "{line}"' for line in lines) + "\n)"


RUN_TEMPLATE = '''"""Smart Buildings remote shard, generated by scripts/remote.py build. Do not edit.

Job {job_id}, shard {shard}, attempt {attempt}, mode {mode}, kernel {kernel}.
Work package SHA-256 {package_sha256}
(code snapshot {code_sha256}, job definition {job_sha256}).
The embedded payload is checked against these values before anything runs.
"""
JOB_ID = {job_id!r}
SHARD = {shard!r}
ATTEMPT = {attempt!r}
MODE = {mode!r}
KERNEL = {kernel!r}
CODE_SHA256 = {code_sha256!r}
JOB_SHA256 = {job_sha256!r}
PACKAGE_SHA256 = {package_sha256!r}
INPUTS_JSON = {inputs_json!r}
CODE_ZIP_B64 = {code_b64}
JOB_JSON_B64 = {job_b64}


def main():
    import base64
    import hashlib
    import io
    import json
    import os
    from pathlib import Path
    import sys
    import tempfile
    import zipfile

    code = base64.b64decode("".join(CODE_ZIP_B64))
    job_bytes = base64.b64decode("".join(JOB_JSON_B64))
    if hashlib.sha256(code).hexdigest() != CODE_SHA256:
        raise SystemExit("code snapshot SHA-256 mismatch; refusing to run")
    if hashlib.sha256(job_bytes).hexdigest() != JOB_SHA256:
        raise SystemExit("job definition SHA-256 mismatch; refusing to run")
    if hashlib.sha256((CODE_SHA256 + "\\n" + JOB_SHA256 + "\\n").encode("ascii")).hexdigest() != PACKAGE_SHA256:
        raise SystemExit("work package SHA-256 mismatch; refusing to run")
    work = os.environ.get("SB_REMOTE_WORK_DIR")
    if not work:
        kaggle_temp = Path("/kaggle/temp")
        base = kaggle_temp if kaggle_temp.is_dir() and os.access(kaggle_temp, os.W_OK) else Path(tempfile.gettempdir())
        work = str(base / ("sb-" + JOB_ID + "-" + SHARD))
        os.environ["SB_REMOTE_WORK_DIR"] = work
    code_dir = Path(work) / "code"
    with zipfile.ZipFile(io.BytesIO(code)) as archive:
        for name in archive.namelist():
            if name.startswith("/") or ".." in Path(name).parts:
                raise SystemExit("unsafe path in code snapshot: " + name)
        archive.extractall(code_dir)
    sys.path.insert(0, str(code_dir / "packages"))
    from smart_building.remote import runner
    package = {{"package_sha256": PACKAGE_SHA256, "code_sha256": CODE_SHA256,
               "job_sha256": JOB_SHA256, "code_root": str(code_dir), "attempt": ATTEMPT,
               "kernel": KERNEL, "inputs": json.loads(INPUTS_JSON)}}
    raise SystemExit(runner.main(json.loads(job_bytes.decode("utf-8")), SHARD, MODE, package))


if __name__ == "__main__":
    main()
'''


def render_run_py(*, job_id, shard, attempt, mode, kernel, code_zip, job_bytes, inputs):
    code_sha256, job_sha256 = sha256_bytes(code_zip), sha256_bytes(job_bytes)
    return RUN_TEMPLATE.format(
        job_id=job_id, shard=shard, attempt=attempt, mode=mode, kernel=kernel,
        code_sha256=code_sha256, job_sha256=job_sha256,
        package_sha256=package_sha256(code_sha256, job_sha256),
        inputs_json=json.dumps(inputs or [], sort_keys=True),
        code_b64=_b64_literal(code_zip), job_b64=_b64_literal(job_bytes))


def kernel_title(job_id, shard, attempt, mode):
    words = ["sb", job_id, shard]
    if mode == "smoke":
        words.append("smoke")
    if attempt != "a":
        words.append(attempt)
    return " ".join(words)


def kernel_metadata(user, title, kernel_sources=()):
    """Private, no internet, no accelerator, competition data mounted (remote plan §3.3, §2)."""
    slug = slugify(title)
    if not slug.startswith("sb-"):
        raise ValueError("kernel names must start with sb- (remote plan §2)")
    return {"id": f"{user}/{slug}", "title": title, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": False,
            "enable_internet": False, "dataset_sources": [], "competition_sources": [COMPETITION],
            "kernel_sources": list(kernel_sources), "model_sources": []}

"""Pipeline 5 stage 丁, rule optimisation (2026-11-04, docs/plan/pipeline5-plan-20261104.md §二丁): a split-plot
two-level design on the surviving option levels, main effects plus pairwise interactions, with a sub-plot fold-over;
the fit and the cost-weighted choice of the best combination.

Factors: one per surviving option (its best level on the track). Building and AHU levels are whole-plot factors,
room levels sub-plot factors. Design: a regular 2^(k-p) fraction on m basic factors (N = 2^m runs); whole-plot
factors only take columns generated by the whole-plot basic factors (Bingham-Sitter split-plot fractions), sub-plot
factors columns that contain a sub-plot basic factor. Columns are chosen greedily: main effects clear of every
two-factor interaction first, then as many interactions estimable as possible. The sub-plot fold-over (every sub-plot
column reversed, the whole plots repeated) is added when it makes more interactions estimable; the smallest design
that estimates every main effect and every pairwise interaction within the run budget wins, otherwise the one that
estimates the most. Interactions that stay aliased are reported as alias groups (the first one carries the group).
In simulation the whole plots are not restricted in randomisation; the split keeps whole-plot effects confounded
only with whole-plot effects, and every effect's standard error comes from its spread over the scenarios.

Fit: per scenario, y = cost / base cost - 1 on the coded factors (+1 on, -1 off) with an intercept, main effects and
the estimable interactions (the all-off base record is one more row). Coefficients are pooled cost-weighted (weight =
the scenario's screen weight x base cost), so a combination's predicted change is the cost-weighted change of the
66-scenario population. An interaction counts only when |mean| > 2 SE (else 0). The chosen combination minimises the
predicted change (all 2^k when k <= 18, else a greedy search from several starts); ties go to fewer options on.
numpy only."""
import itertools
import math

import numpy as np

MIN_T_2FI = 2.0


def _cols(m, whole_bits):
    """Columns of the 2^m full factorial: bitmask -> +-1 vector; whole-only masks use only whole-plot bits."""
    base = np.array(list(itertools.product((-1, 1), repeat=m)), dtype=float)[:, ::-1]      # bit j = column j
    out = {}
    for mask in range(1, 2 ** m):
        v = np.ones(2 ** m)
        for j in range(m):
            if mask >> j & 1:
                v = v * base[:, j]
        out[mask] = v
    whole_mask = (1 << whole_bits) - 1
    whole = [k for k in out if k & ~whole_mask == 0]
    sub = [k for k in out if k & ~whole_mask]
    return out, whole, sub


def model_terms(k, whole_idx):
    """Main effects then pairwise interactions (whole x whole, whole x sub, sub x sub)."""
    me = [(i,) for i in range(k)]
    pairs = list(itertools.combinations(range(k), 2))
    w = set(whole_idx)
    pairs.sort(key=lambda p: (-(p[0] in w) - (p[1] in w), p))
    return me, pairs


def term_matrix(X, terms):
    cols = [np.ones(len(X))]
    for t in terms:
        v = np.ones(len(X))
        for i in t:
            v = v * X[:, i]
        cols.append(v)
    return np.column_stack(cols)


def evaluate(X, whole_idx):
    """(main effects clear of all 2FIs and of each other, number of estimable 2FIs, alias groups of the rest)."""
    # regular fractions (and their fold-overs): two term columns are either orthogonal or equal up to sign, so the
    # aliasing is read off sign-normalised column keys
    k = X.shape[1]
    _, pairs = model_terms(k, whole_idx)
    n = len(X)

    def key(v):
        v = v if v[0] > 0 else -v
        return v.astype(np.int8).tobytes()

    owner = {key(np.ones(n)): "I"}
    clear = True
    for i in range(k):
        kk = key(X[:, i])
        if kk in owner:
            clear = False
        owner.setdefault(kk, f"ME{i}")
    kept, alias = [], {}
    for p in pairs:
        kk = key(X[:, p[0]] * X[:, p[1]])
        if kk in owner:
            if not isinstance(owner[kk], tuple):
                clear = False                                 # a main effect (or the mean) aliased with a 2FI
            alias.setdefault(str(owner[kk]), []).append(p)
        else:
            owner[kk] = p
            kept.append(p)
    return clear, kept, alias


def make(whole, sub, max_runs=64, seed=0):
    """Design for whole-plot and sub-plot factor names. Returns dict(rows (+-1 lists), names, whole_idx, runs, base
    runs, foldover, estimable pairs, alias groups, full)."""
    names = list(whole) + list(sub)
    a, b = len(whole), len(sub)
    k = a + b
    whole_idx = list(range(a))
    if k == 0:
        raise ValueError("no factors")
    best = None
    for m in range(max(1, math.ceil(math.log2(k + 1))), 11):
        N = 2 ** m
        if N > max_runs:
            break
        for mw in range(0, m + 1):
            if (2 ** mw - 1) < a or (a > 0 and mw == 0) or (b > 0 and mw == m) or (2 ** m - 2 ** mw) < b:
                continue
            cols, wcols, scols = _cols(m, mw)
            for fold in ((False, True) if b else (False,)):
                if fold and 2 * N > max_runs:
                    continue
                chosen = []

                def design(masks):
                    X = np.column_stack([cols[c] for c in masks]) if masks else np.zeros((N, 0))
                    if fold:
                        Y = X.copy()
                        Y[:, a:len(masks)] *= -1 if len(masks) > a else 1
                        X = np.vstack([X, Y])
                    return X

                ok = True
                for i in range(k):
                    pool = [c for c in (wcols if i < a else scols) if c not in chosen]
                    # basic columns first (one bit), then higher-order generators
                    single = [c for c in pool if bin(c).count("1") == 1]
                    best_c, best_s = None, None
                    for c in (single[:1] if single else sorted(pool, key=lambda c: (-bin(c).count("1"), c))):
                        X = design(chosen + [c])
                        clear, kept, _ = evaluate(X, [j for j in whole_idx if j <= i])
                        s = (clear, len(kept), bin(c).count("1"))
                        if best_s is None or s > best_s:
                            best_c, best_s = c, s
                    if best_c is None:
                        ok = False
                        break
                    chosen.append(best_c)
                if not ok:
                    continue
                X = design(chosen)
                if len({tuple(r) for r in X}) < len(X):          # duplicated runs: the fold-over adds nothing
                    if fold:
                        continue
                clear, kept, alias = evaluate(X, whole_idx)
                full = clear and len(kept) == k * (k - 1) // 2
                score = (clear, full, len(kept), -len(X))
                cand = {"names": names, "whole": list(whole), "sub": list(sub), "whole_idx": whole_idx,
                        "rows": X.astype(int).tolist(), "runs": len(X), "base_runs": N, "foldover": fold,
                        "masks": chosen, "whole_bits": mw, "basic": m, "me_clear": clear,
                        "pairs": [[names[i], names[j]] for i, j in kept], "pairs_idx": [list(p) for p in kept],
                        "alias": {_label(g, names): [[names[i], names[j]] for i, j in v] for g, v in alias.items()},
                        "full": full}
                if best is None or score > best[0]:
                    best = (score, cand)
        if best is not None and best[1]["full"]:
            break
    if best is None:
        raise ValueError(f"no design for {a} whole-plot and {b} sub-plot factors within {max_runs} runs")
    return best[1]


def _label(g, names):
    if g == "I":
        return "mean"
    if g.startswith("ME"):
        return names[int(g[2:])]
    i, j = (int(x) for x in g.strip("()").split(","))
    return f"{names[i]} x {names[j]}"


# ---------------------------------------------------------------- fit and choice
def fit(design, y_by_scen, weight_by_scen):
    """y_by_scen: scenario -> list of y per design row (+ the all-off row last, levels all -1); weight: scenario ->
    screen weight x base cost. Returns per-term pooled mean / se and the per-scenario coefficients."""
    k = len(design["names"])
    terms = [(i,) for i in range(k)] + [tuple(p) for p in design["pairs_idx"]]
    rows = np.array(design["rows"] + [[-1] * k], dtype=float)
    M = term_matrix(rows, terms)
    per = {}
    for s, y in y_by_scen.items():
        beta, *_ = np.linalg.lstsq(M, np.asarray(y, dtype=float), rcond=None)
        per[s] = beta
    scen = sorted(per)
    B = np.array([per[s] for s in scen])
    w = np.array([weight_by_scen[s] for s in scen], dtype=float)
    w = w / w.sum()
    mean = w @ B
    n_eff = 1.0 / float(np.sum(w ** 2))
    var = (w @ (B - mean) ** 2) / max(1e-12, 1.0 - float(np.sum(w ** 2)))
    se = np.sqrt(var / n_eff)
    use = np.ones(len(mean), dtype=bool)
    for j, t in enumerate(terms, start=1):
        if len(t) == 2 and not abs(mean[j]) > MIN_T_2FI * se[j]:
            use[j] = False
    return {"terms": terms, "mean": mean.tolist(), "se": se.tolist(), "use": use.tolist(), "n": len(scen),
            "n_eff": n_eff, "per_scenario": {s: per[s].tolist() for s in scen}}


def predict(fitres, x, coef=None):
    """Predicted change (share of the base cost) of combination x (+-1 per factor) against all off."""
    coef = np.asarray(coef if coef is not None else fitres["mean"], dtype=float)
    use = np.asarray(fitres["use"], dtype=bool)
    x = np.asarray(x, dtype=float)
    x0 = -np.ones(len(x))
    tx = term_matrix(x[None, :], fitres["terms"])[0]
    t0 = term_matrix(x0[None, :], fitres["terms"])[0]
    return float(np.sum((coef * use) * (tx - t0)))


def choose(fitres, k, seed=0):
    """Best combination (min predicted change; ties to fewer options on)."""
    best = None
    if k <= 18:
        for bits in range(2 ** k):
            x = [1 if bits >> i & 1 else -1 for i in range(k)]
            p = predict(fitres, x)
            key = (round(p, 12), sum(v > 0 for v in x))
            if best is None or key < best[0]:
                best = (key, x, p)
    else:
        rng = np.random.default_rng(seed)
        for start in range(20):
            x = [-1] * k if start == 0 else [int(v) for v in rng.choice([-1, 1], size=k)]
            improved = True
            while improved:
                improved = False
                for i in range(k):
                    y = list(x)
                    y[i] = -y[i]
                    if predict(fitres, y) < predict(fitres, x) - 1e-12:
                        x, improved = y, True
            p = predict(fitres, x)
            key = (round(p, 12), sum(v > 0 for v in x))
            if best is None or key < best[0]:
                best = (key, x, p)
    return best[1], best[2]


def per_scenario_prediction(fitres, x):
    use = np.asarray(fitres["use"], dtype=bool)
    out = {}
    for s, beta in fitres["per_scenario"].items():
        out[s] = predict({**fitres, "use": use.tolist()}, x, coef=beta)
    return out

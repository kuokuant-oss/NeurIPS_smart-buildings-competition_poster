"""Write the policy module of a Kaggle gate job: G36PolicyB2RL bound to one exported actor (user 2026-10-28 08:3x: "看能
不能用kaggle cpu 五台去驗證"). A remote job's code snapshot never packs data/, so the exported actor goes into the
module as a JSON string, the way scripts/build_submission.py embeds it in the competition notebook. The module holds
model weights (derived data); it must be listed in .gitignore. Host python3, standard library.

python3 -B pipeline/setup/b2rl_gate_policy.py [model.json module_stem ClassName]
  default: data/runs/b2rl/full-rom-s42-15M/model.json b2rl_full15m G36PolicyB2RLFull15M (job j14b)"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
ARGS = sys.argv[1:] or ["data/runs/b2rl/full-rom-s42-15M/model.json", "b2rl_full15m", "G36PolicyB2RLFull15M"]
MODEL = ROOT / ARGS[0]
MODULE = ROOT / "packages/smart_building/policies" / f"{ARGS[1]}.py"
CLASS = ARGS[2]


def main():
    model = json.loads(MODEL.read_text(encoding="utf-8"))
    digest = hashlib.sha256(MODEL.read_bytes()).hexdigest()
    source = model["source"]
    MODULE.write_text(
        f'"""G36PolicyB2RL bound to {MODEL.relative_to(ROOT).as_posix()}, for a Kaggle gate job.\n\n'
        f"Generated by pipeline/setup/b2rl_gate_policy.py (model sha256 {digest};\n"
        f"checkpoint {Path(source['checkpoint']).name}, update {source['update']}, {source['decisions']} decisions, "
        f"seed {source['seed']}{'; ' + source['offset_check'] if source.get('offset_check') else ''}).\n"
        "It holds model weights (derived data), so it is listed in .gitignore.\n"
        '"""\n'
        "from smart_building.policies.b2rl import b2rl_policy_class\n\n"
        f"MODEL_SHA256 = {digest!r}\n"
        f"MODEL_JSON = {json.dumps(model, separators=(',', ':'))!r}\n\n"
        f"{CLASS} = b2rl_policy_class(MODEL_JSON)\n",
        encoding="utf-8", newline="\n")
    print(f"{MODULE.relative_to(ROOT)}: {MODULE.stat().st_size} bytes, model sha256 {digest[:12]}")


if __name__ == "__main__":
    main()

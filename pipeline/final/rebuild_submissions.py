"""Rebuild the notebooks of the two final controllers and compare them with data/submissions/<name>.

Same command as the submission (scripts/build_submission.py, policy class G36PolicyB2RL, model JSON embedded); the
builder only needs the standard library. The rebuilt notebook, with its one build-date line set to the shipped one's,
must be byte-identical to the shipped notebook, and every embedded source must have the SHA-256 recorded in
embedded-files.json. Nothing is pushed to Kaggle.
python3 -B pipeline/final/rebuild_submissions.py"""
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SUBMITTED = {"gt-x8": ("gt_x8", "public 0.01056"), "pr-opt2": ("pr_opt2", "public 0.01071")}
DATE_LINE = re.compile(r"Generated by `scripts/build_submission.py` on \d{4}-\d{2}-\d{2}\.")


def main():
    ok = True
    for name, (model, score) in SUBMITTED.items():
        sub = ROOT / "data/submissions" / name
        out = ROOT / "data/final/rebuild-submissions" / name
        cmd = [sys.executable, "-B", "scripts/build_submission.py", "--policy-class", "G36PolicyB2RL",
               "--slug", f"sb-{name}", "--title", f"SB {name}", "--username", "antonktt",
               "--out", str(out.relative_to(ROOT)), "--embed", f"data/runs/b2rl/search/models/model-{model}.json"]
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        print(f"--- {name} ({score}): build exit {r.returncode}")
        if r.returncode:
            print(r.stdout[-1500:], r.stderr[-1500:])
            ok = False
            continue
        shipped = (sub / f"sb-{name}.ipynb").read_text(encoding="utf-8")
        built = DATE_LINE.sub(DATE_LINE.search(shipped).group(0),
                              (out / f"sb-{name}.ipynb").read_text(encoding="utf-8"))
        want = json.loads((sub / "embedded-files.json").read_text())
        got = json.loads((out / "embedded-files.json").read_text())
        nb_same = built == shipped
        src_same = got["embedded"] == want["embedded"]
        meta_same = (out / "kernel-metadata.json").read_bytes() == (sub / "kernel-metadata.json").read_bytes()
        ok &= nb_same and src_same and meta_same
        print(f"   notebook: {'identical' if nb_same else 'DIFFERENT'}; {len(want['embedded'])} embedded sources: "
              f"{'identical' if src_same else 'DIFFERENT'}; kernel-metadata.json: {'identical' if meta_same else 'DIFFERENT'}")
    print("ALL IDENTICAL" if ok else "SOME DIFFER")
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()

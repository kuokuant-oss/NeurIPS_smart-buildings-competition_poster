"""Rebuild the two Kaggle notebooks of the paper's final controllers and compare them with the submitted ones.

Same command as the submission (scripts/build_submission.py, policy class G36PolicyB2RL, model JSON embedded); the
builder only needs the standard library. Nothing is pushed to Kaggle.

What is compared:
- every embedded source file against the SHA-256 recorded at submission (data/submissions/<name>/embedded-files.json);
- the whole notebook, byte for byte, against data/submissions/<name>/<notebook>.ipynb, after its one build-date line is
  set to the submission's date.
The files in this repository differ from the submitted ones in one string only: the absolute path of the training
machine's working directory, recorded as metadata in the models' `source` field (never read by the controller), is
written as /home/user/. With ORIGINAL_HOME set to the training machine's home directory, the rebuilt notebook is also
compared with the SHA-256 of the submitted notebook (embedded-files.json, notebook_sha256).
python3 -B pipeline/final/rebuild_submissions.py"""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
SUBMITTED = {"gt-x8": ("gt_x8", "0.01056, Kaggle submission 58255120"),
             "pr-opt2": ("pr_opt2", "0.01071, Kaggle submission 58270357")}
DATE_LINE = re.compile(r"Generated by `scripts/build_submission.py` on \d{4}-\d{2}-\d{2}\.")


def main():
    ok = True
    original = os.environ.get("ORIGINAL_HOME")
    for name, (model, score) in SUBMITTED.items():
        sub = ROOT / "data/submissions" / name
        out = ROOT / "data/final/rebuild-submissions" / name
        cmd = [sys.executable, "-B", "scripts/build_submission.py", "--policy-class", "G36PolicyB2RL",
               "--slug", f"sb-{name}", "--title", f"SB {name}", "--username", "antonktt",
               "--out", str(out.relative_to(ROOT)), "--embed", f"data/runs/b2rl/search/models/model-{model}.json"]
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        print(f"--- {name} (public {score}): build exit {r.returncode}")
        if r.returncode:
            print(r.stdout[-1500:], r.stderr[-1500:])
            ok = False
            continue
        shipped_nb = (sub / f"sb-{name}.ipynb").read_text(encoding="utf-8")
        built_nb = (out / f"sb-{name}.ipynb").read_text(encoding="utf-8")
        built_nb = DATE_LINE.sub(DATE_LINE.search(shipped_nb).group(0), built_nb)
        want = json.loads((sub / "embedded-files.json").read_text())
        got = json.loads((out / "embedded-files.json").read_text())
        nb_same = built_nb == shipped_nb
        # the embedded model JSON's own hash is the one entry that follows the path replacement: compare it with the
        # shipped model file (and, with ORIGINAL_HOME, with the submission's below)
        strip = lambda rows: [{k: v for k, v in e.items() if k != "embedded_json_sha256"} for e in rows]
        model_file = ROOT / f"data/runs/b2rl/search/models/model-{model}.json"
        model_rows = [e for e in got["embedded"] if "embedded_json_sha256" in e]
        src_same = strip(got["embedded"]) == strip(want["embedded"]) and all(
            e["embedded_json_sha256"] == hashlib.sha256(model_file.read_bytes()).hexdigest() for e in model_rows)
        meta_same = (out / "kernel-metadata.json").read_bytes() == (sub / "kernel-metadata.json").read_bytes()
        ok &= nb_same and src_same and meta_same
        print(f"   notebook: {'identical' if nb_same else 'DIFFERENT'} to data/submissions/{name} "
              f"(build-date line set to the submission's)")
        print(f"   {len(want['embedded'])} embedded sources: {'identical' if src_same else 'DIFFERENT'} to the "
              f"submission's SHA-256 (the model JSON's to the shipped model file); kernel-metadata.json: "
              f"{'identical' if meta_same else 'DIFFERENT'}")
        if original:
            home = original.rstrip("/") + "/"
            restored = built_nb.replace("/home/user/", home)
            sub_same = hashlib.sha256(restored.encode("utf-8")).hexdigest() == want["notebook_sha256"]
            m_restored = model_file.read_bytes().replace(b"/home/user/", home.encode())
            m_want = [e["embedded_json_sha256"] for e in want["embedded"] if "embedded_json_sha256" in e]
            m_same = all(hashlib.sha256(m_restored).hexdigest() == h for h in m_want)
            ok &= sub_same and m_same
            print(f"   with the original path: notebook sha256 {'identical' if sub_same else 'DIFFERENT'} to the "
                  f"submitted one ({want['notebook_sha256'][:16]}); model JSON sha256 "
                  f"{'identical' if m_same else 'DIFFERENT'} to the embedded one ({m_want[0][:16]})")
    print("ALL IDENTICAL" if ok else "SOME DIFFER")
    raise SystemExit(0 if ok else 1)


if __name__ == "__main__":
    main()
